#!/usr/bin/env node
/**
 * build-seed.js - write supabase/seed-from-config.sql from config/*.json, and
 * supabase/setup-all.sql: every setup file in run order, as one paste.
 *
 * The intake tables foreign-key against pulse_sources and pulse_departments,
 * so a source that exists in config/sources.json but not in the database makes
 * every upload for it fail. Hand-written seed rows drift; this does not.
 *
 * Seeds are `on conflict do nothing` (or only fill blanks), so re-running never
 * overwrites what someone already set through the UI.
 *
 *   node bin/build-seed.js
 */

import { readFile, writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = async (p) => JSON.parse(await readFile(join(ROOT, p), 'utf8'));

const lit = (v) => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (Array.isArray(v)) return `array[${v.map(lit).join(',')}]::text[]`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const PLACEHOLDER = { gsheet: 'REPLACE_WITH_SPREADSHEET_ID', notion: 'REPLACE_WITH_DATABASE_ID' };

export async function buildSeed() {
  const [org, sources, meetings] = await Promise.all([
    read('config/org.json'), read('config/sources.json'), read('config/meetings.json')
  ]);

  const out = [
    '-- GENERATED by bin/build-seed.js from config/*.json. Do not edit by hand.',
    '-- Run AFTER schema.sql and schema-app.sql. Safe to run again.',
    ''
  ];

  out.push('-- Sources: every one in config/sources.json, so uploads have a row to point at.');
  out.push('insert into pulse_sources (id, dept_id, kind, label, ref, tab, header_row, date_column, row_timestamp_column, segment) values');
  out.push(sources.sources.map((s) => `  (${[
    s.id, s.dept, s.kind, s.label,
    s.ref && !String(s.ref).startsWith('REPLACE') ? s.ref : (PLACEHOLDER[s.kind] || s.ref || null),
    s.tab || null, s.header_row || 1, s.date_column || null, s.row_timestamp_column || null, s.segment || null
  ].map(lit).join(', ')})`).join(',\n'));
  out.push('on conflict (id) do nothing;', '');

  out.push('-- Owners: fill the department row only where nobody has set one yet.');
  for (const [id, owner] of Object.entries(org.owners || {})) {
    const team = (owner.team || []).filter(Boolean);
    if (!team.length) continue;
    out.push(`update pulse_departments set owner_name = ${lit(owner.lead || team.join(', '))} where id = ${lit(id)} and owner_name is null;`);
  }
  out.push('');

  // configload.js prefers database meeting kinds over meetings.json whenever
  // any row exists, so the old single-WBR seed row would hide the four real
  // meetings. Replace it with them.
  out.push('-- Meetings: the four weekly rooms from config/meetings.json.');
  out.push("delete from pulse_meeting_kinds where id = 'wbr' and not exists (select 1 from pulse_meeting_kinds where id <> 'wbr');");
  out.push('insert into pulse_meeting_kinds (id, label, short_label, kind, cadence, day, time_of_day, dept_ids, blurb, ord) values');
  out.push(meetings.meetings.map((m, i) => `  (${[
    m.id, m.name || m.id, m.name || m.id, m.id, 'weekly', m.day || null, m.time || null,
    [...new Set((m.members || []).map((x) => (typeof x === 'string' ? x : x.dept)).filter(Boolean))],
    m._note || null, i + 1
  ].map(lit).join(', ')})`).join(',\n'));
  out.push('on conflict (id) do nothing;', '');

  return out.join('\n');
}

const SETUP_ORDER = ['schema.sql', 'schema-app.sql', 'seed-from-config.sql', 'schema-open-today.sql'];

async function main() {
  const seed = await buildSeed();
  await writeFile(join(ROOT, 'supabase/seed-from-config.sql'), seed);

  const parts = ['-- GENERATED by bin/build-seed.js: every setup file, in order, as one paste.',
    `-- ${SETUP_ORDER.join(' -> ')}`, ''];
  for (const f of SETUP_ORDER) {
    parts.push(`-- ${'='.repeat(74)}`, `-- ${f}`, `-- ${'='.repeat(74)}`, await readFile(join(ROOT, 'supabase', f), 'utf8'), '');
  }
  await writeFile(join(ROOT, 'supabase/setup-all.sql'), parts.join('\n'));
  console.log('wrote supabase/seed-from-config.sql and supabase/setup-all.sql');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((err) => { console.error(err.message); process.exit(1); });
}
